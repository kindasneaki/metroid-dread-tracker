#!/usr/bin/env node
/**
 * scripts/gen-location-names.cjs
 *
 * Generates src/logic/locationNames.js — a static room-name map derived from
 * the Randovania logic JSON files in public/logic/.
 *
 * Run:
 *   node scripts/gen-location-names.cjs
 *
 * The script:
 *   1. Reads LOCATION_PICKUP_MAP from src/logic/pickupMatch.js (ESM) via dynamic import.
 *   2. For each region, reads public/logic/<Region>.json and builds a
 *      pickup_index → room (area key) map.
 *   3. Resolves each LOCATION_PICKUP_MAP[region][i] → room name.
 *   4. Self-asserts per-region counts against known-good values.
 *   5. Writes src/logic/locationNames.js with CRLF line endings.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

const EXPECTED_COUNTS = {
  artaria: 35,
  cataris: 25,
  dairon: 23,
  burenia: 20,
  ferenia: 17,
  ghavoran: 20,
  elun: 5,
  hanubia: 4,
};

// Maps lowercase region key → capitalized JSON filename stem
function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

async function main() {
  // 1. Import LOCATION_PICKUP_MAP from the ESM pickupMatch module
  const pickupMatchUrl = new URL(
    "file://" + path.join(ROOT, "src/logic/pickupMatch.js"),
  );
  const { LOCATION_PICKUP_MAP } = await import(pickupMatchUrl.href);

  const LOCATION_NAME_MAP = {};

  for (const region of Object.keys(EXPECTED_COUNTS)) {
    const jsonFile = path.join(
      ROOT,
      "public/logic",
      capitalize(region) + ".json",
    );
    const rdvJson = JSON.parse(fs.readFileSync(jsonFile, "utf8"));

    // 2. Build piToArea: pickup_index → area (room) name
    const piToArea = new Map();
    for (const [areaName, area] of Object.entries(rdvJson.areas)) {
      for (const node of Object.values(area.nodes)) {
        if (node.node_type === "pickup") {
          piToArea.set(node.pickup_index, areaName);
        }
      }
    }

    // 3. Resolve each array index's pickup_index to a room name
    const pickupMap = LOCATION_PICKUP_MAP[region];
    if (!pickupMap) {
      throw new Error(
        `gen-location-names: LOCATION_PICKUP_MAP has no entry for region "${region}".`,
      );
    }

    const names = pickupMap.map((pi, arrayIndex) => {
      const name = piToArea.get(pi);
      if (name === undefined) {
        throw new Error(
          `gen-location-names: region "${region}" array index ${arrayIndex} pickup_index ${pi} ` +
            `not found in ${capitalize(region)}.json — check LOCATION_PICKUP_MAP.`,
        );
      }
      return name;
    });

    // 4. Assert count parity
    const expected = EXPECTED_COUNTS[region];
    if (names.length !== expected) {
      throw new Error(
        `gen-location-names: region "${region}" produced ${names.length} names but expected ${expected}.`,
      );
    }

    LOCATION_NAME_MAP[region] = names;
  }

  // 5. Verify the Drogyga example from the plan
  if (LOCATION_NAME_MAP.burenia[19] !== "Drogyga Arena") {
    throw new Error(
      `gen-location-names: burenia[19] should be "Drogyga Arena" but got "${LOCATION_NAME_MAP.burenia[19]}".`,
    );
  }

  // 6. Emit src/logic/locationNames.js with CRLF line endings
  const lines = [
    "// AUTO-GENERATED by scripts/gen-location-names.cjs — do not hand-edit.",
    "// Re-run the script to regenerate after changing LOCATION_PICKUP_MAP or the logic JSON files.",
    "",
    "/**",
    " * LOCATION_NAME_MAP",
    " *",
    " * Maps each region's tracker array index to the authoritative Randovania room (area) name.",
    " * Indexed as LOCATION_NAME_MAP[region][arrayIndex] === roomName.",
    " *",
    " * Room names are area keys from public/logic/<Region>.json (not item names — those are",
    " * randomized). Duplicate room names across markers are expected; position disambiguates.",
    " */",
    "export const LOCATION_NAME_MAP = {",
  ];

  for (const [region, names] of Object.entries(LOCATION_NAME_MAP)) {
    // Emit each region as a compact array of quoted strings, 4 per line
    const quoted = names.map((n) => JSON.stringify(n));
    const chunks = [];
    for (let i = 0; i < quoted.length; i += 4) {
      chunks.push("    " + quoted.slice(i, i + 4).join(", ") + ",");
    }
    lines.push(`  ${region}: [`);
    for (const chunk of chunks) {
      lines.push(chunk);
    }
    lines.push("  ],");
  }

  lines.push("};");
  lines.push("");
  lines.push("/**");
  lines.push(
    " * locationNameFor(region, index)",
    " *",
    " * Return the room name for a tracker location.",
    " *",
    " * @param {string} region - lower-case region key, e.g. \"artaria\"",
    " * @param {number} index  - 0-based tracker array index",
    " * @returns {string} the Randovania room name, or a graceful fallback on out-of-range index",
    " * @throws {Error} if region is unknown",
    " */",
  );
  lines.push("export function locationNameFor(region, index) {");
  lines.push("  const names = LOCATION_NAME_MAP[region];");
  lines.push("  if (!names) {");
  lines.push(
    '    throw new Error(`locationNameFor: unknown region "${region}". Known: ${Object.keys(LOCATION_NAME_MAP).join(", ")}.`);',
  );
  lines.push("  }");
  lines.push("  if (index < 0 || index >= names.length) {");
  lines.push(
    "    // Graceful fallback: return the capitalized region name rather than crashing the UI.",
  );
  lines.push(
    "    return region.charAt(0).toUpperCase() + region.slice(1);",
  );
  lines.push("  }");
  lines.push("  return names[index];");
  lines.push("}");
  lines.push("");

  // Join with CRLF (Prettier CRLF requirement per CLAUDE.md)
  const content = lines.join("\r\n");

  const outPath = path.join(ROOT, "src/logic/locationNames.js");
  fs.writeFileSync(outPath, content, "utf8");

  // Summary
  console.log("gen-location-names: wrote " + outPath);
  for (const [region, names] of Object.entries(LOCATION_NAME_MAP)) {
    console.log(
      `  ${region}: ${names.length} entries (expected ${EXPECTED_COUNTS[region]}) ✓`,
    );
  }
  console.log('  burenia[19] === "Drogyga Arena" ✓');
  console.log("gen-location-names: all assertions passed.");
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
